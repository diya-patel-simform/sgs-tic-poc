"""SGS TIC Bot — Streamlit chat UI on top of the existing RAG backend.

    User question -> ticbot_chunking.rag.rag_service.answer() -> grounded
    answer + structured citations + retrieved chunks (RagResponse)

This module contains NO retrieval, embedding, or Azure OpenAI logic of its
own — it only calls `rag_service.answer()` (which itself only calls the
existing `search/retrieval_client.py`) and renders the resulting
`RagResponse`. Chat history lives in `st.session_state` only — no database,
no persistence across a browser refresh or a new session.

Run with (from the project root):
    streamlit run ticbot_chunking/app.py
"""
from __future__ import annotations

import sys
from pathlib import Path

# `streamlit run` puts this file's own directory (ticbot_chunking/) on
# sys.path, not the project root — so the absolute `ticbot_chunking.*`
# imports below would otherwise fail with "No module named 'ticbot_chunking'"
# even when launched with the documented command from the project root.
# Inserting the project root here makes this script runnable the same way
# regardless of how Streamlit itself sets up sys.path.
_PROJECT_ROOT = str(Path(__file__).resolve().parent.parent)
if _PROJECT_ROOT not in sys.path:
    sys.path.insert(0, _PROJECT_ROOT)

import streamlit as st

from ticbot_chunking.config import OPENAI, SEARCH
from ticbot_chunking.rag.rag_service import answer as rag_answer
from ticbot_chunking.rag.response import Citation, RagResponse

STRATEGY = "hybrid"  # the document-type-aware strategy; see README "RAG backend"
# TEMPORARY: pointed at the updated-pdf-data indexes for testing that
# dataset specifically. Revert to None (the default ticbot-chunks-<strategy>
# index) to go back to the original sample dataset.
INDEX_NAME_OVERRIDE = f"ticbot-chunks-{STRATEGY}-updated"
# Retrieval mode is fixed per deployment (config.SEARCH.retrieval_mode,
# default "vector" — see that field's docstring), not user-selectable in
# the UI: manual testing found keyword mode unreliable (it ranked the
# wrong document's chunk #1 on several regulation questions), so there is
# no mode picker here any more.
MODE_LABELS = {"hybrid": "Hybrid", "vector": "Vector", "keyword": "Keyword"}


def _config_status() -> list[tuple[str, bool]]:
    """Boolean configured/not-configured per component — never the actual
    endpoint, key, or deployment values themselves."""
    return [
        ("Azure AI Search", SEARCH.is_configured),
        ("Azure OpenAI (embeddings)", OPENAI.is_configured),
        ("Azure OpenAI chat deployment", bool(OPENAI.chat_deployment)),
    ]


def _render_citation(citation: Citation, retrieved_chunks) -> None:
    # `source_numbers` already carries every [N] this (deduplicated)
    # citation represents — e.g. [1][3] if the model cited the same
    # source_file+section twice under different retrieved chunks (see
    # rag_service._dedupe_citations) — so this never renders the same
    # source_file+section as two separate blocks.
    label = "".join(f"[{n}]" for n in citation.source_numbers) + " " if citation.source_numbers else ""
    st.markdown(f"**{label}{citation.source_file or 'Unknown source'}**")
    details = []
    if citation.document_type:
        details.append(f"Document type: {citation.document_type}")
    if citation.page:
        details.append(f"Page(s): {citation.page}")
    if citation.sheet:
        details.append(f"Sheet: {citation.sheet}")
    if citation.cell_range:
        details.append(f"Cell range: {citation.cell_range}")
    if citation.section:
        details.append(f"Section: {citation.section}")
    if citation.certificate_no:
        details.append(f"Certificate no.: {citation.certificate_no}")
    if citation.lab_location:
        details.append(f"Laboratory: {citation.lab_location}")
    if citation.discipline:
        details.append(f"Discipline: {citation.discipline}")
    if citation.material:
        details.append(f"Material: {citation.material}")
    for line in details:
        st.caption(line)

    # A cited table-type chunk's own real, mechanically-generated markdown
    # table (built from structured row data at chunk-creation time — see
    # chunkers/table_utils.py — never regenerated by the LLM) is rendered
    # directly as a table here, rather than left as plain prose.
    chunk = next((c for c in retrieved_chunks if c.chunk_id == citation.chunk_id), None)
    if chunk is not None and chunk.chunk_type == "table" and chunk.text:
        table_lines = [line for line in chunk.text.splitlines() if line.strip().startswith("|")]
        if len(table_lines) >= 2:  # a header + separator/row, at minimum
            st.markdown("\n".join(table_lines))


def _render_retrieved_chunk(result) -> None:
    header = f"[{result.rank}] {result.source_file or 'unknown'}"
    if result.score is not None:
        header += f"  (score: {result.score:.4f})"
    with st.expander(header, expanded=False):
        meta = []
        if result.document_type:
            meta.append(f"Document type: {result.document_type}")
        if result.pages:
            meta.append(f"Page(s): {', '.join(str(p) for p in result.pages)}")
        if result.sheet:
            meta.append(f"Sheet: {result.sheet}")
        if result.cell_range:
            meta.append(f"Cell range: {result.cell_range}")
        section = result.section_path or result.section_number
        if section:
            meta.append(f"Section: {section}")
        if result.certificate_no:
            meta.append(f"Certificate no.: {result.certificate_no}")
        if result.lab_location:
            meta.append(f"Laboratory: {result.lab_location}")
        if result.discipline:
            meta.append(f"Discipline: {result.discipline}")
        if result.material:
            meta.append(f"Material: {result.material}")
        for line in meta:
            st.caption(line)
        st.text(result.text or "")


def render_response(response: RagResponse) -> None:
    """Renders one RagResponse: the grounded answer, its citations, and an
    expandable section with every retrieved chunk (cited or not)."""
    st.markdown(response.answer)

    st.markdown(f"**Citations** (retrieval mode: {MODE_LABELS.get(response.retrieval_mode, response.retrieval_mode)}, "
                f"top_k: {response.top_k})")
    if response.citations:
        for citation in response.citations:
            _render_citation(citation, response.retrieved_chunks)
    else:
        st.caption("No citations — the answer above did not draw on the retrieved sources.")

    with st.expander(f"Retrieved sources ({len(response.retrieved_chunks)})", expanded=False):
        if not response.retrieved_chunks:
            st.caption("No results were retrieved for this question.")
        for result in response.retrieved_chunks:
            _render_retrieved_chunk(result)


def _handle_question(question: str, mode: str, top_k: int) -> RagResponse | None:
    question = question.strip()
    if not question:
        st.warning("Please enter a question.")
        return None

    try:
        return rag_answer(question, strategy=STRATEGY, mode=mode, top_k=top_k, index_name=INDEX_NAME_OVERRIDE)
    except RuntimeError as e:
        # require_chat_client() / the retrieval client's require_search_client()
        # raise RuntimeError with a clear, specific message for a missing/bad
        # Azure configuration — surfaced as-is, never as a raw traceback.
        st.error(f"Configuration error: {e}")
        return None
    except Exception as e:
        st.error(f"The RAG service could not complete this request: {type(e).__name__}: {e}")
        return None


def main() -> None:
    st.set_page_config(page_title="SGS TIC Bot", page_icon="🧪", layout="wide")
    st.title("SGS TIC Bot")
    st.caption("Grounded answers over SGS testing/inspection/certification documents — "
               "every statement is traceable to a retrieved source, never invented.")

    if "messages" not in st.session_state:
        st.session_state.messages = []  # session-only chat history — no database, no persistence

    mode = SEARCH.retrieval_mode

    with st.sidebar:
        st.header("Settings")
        top_k = st.number_input("Top-K", min_value=1, max_value=20, value=5, step=1,
                                 help="How many chunks to retrieve per question.")

        st.divider()
        st.subheader("Configuration status")
        for label, ok in _config_status():
            st.markdown(f"{'✅' if ok else '❌'} {label}")

        st.divider()
        st.subheader("Index")
        active_index = INDEX_NAME_OVERRIDE or f"ticbot-chunks-{STRATEGY}"
        st.caption(f"Strategy: {STRATEGY}")
        st.caption(f"Index: {active_index}")
        if INDEX_NAME_OVERRIDE:
            st.caption("⚠️ Testing the updated-pdf-data dataset, not the original sample dataset.")
        st.caption(f"Retrieval mode: {MODE_LABELS.get(mode, mode)}")

        st.divider()
        if st.button("Clear chat"):
            st.session_state.messages = []
            st.rerun()

    for message in st.session_state.messages:
        with st.chat_message(message["role"]):
            if message["role"] == "assistant":
                render_response(message["response"])
            else:
                st.markdown(message["content"])

    question = st.chat_input("Ask a question about the SGS documents...")
    if question:
        st.session_state.messages.append({"role": "user", "content": question})
        with st.chat_message("user"):
            st.markdown(question)

        with st.chat_message("assistant"):
            with st.spinner("Retrieving sources and generating a grounded answer..."):
                response = _handle_question(question, mode, int(top_k))
            if response is not None:
                render_response(response)
                st.session_state.messages.append({"role": "assistant", "response": response})
            else:
                # A config/service error was already shown via st.error above;
                # drop the unanswered user turn rather than leaving a
                # dangling question with no assistant reply in history.
                st.session_state.messages.pop()


if __name__ == "__main__":
    main()
